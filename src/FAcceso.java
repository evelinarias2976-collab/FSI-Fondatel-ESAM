    private void BAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BAceptarActionPerformed

        String usr = TUsuario.getText().trim();
        String nip = new String(TPassword.getPassword());

        if (usr.isEmpty() || nip.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingresa tu usuario y NIP");
            return;
        }

        String sql = String.format(rol, usr, nip);
        String tipo = cnx.obtenerDato(sql);

        switch (tipo) {
            case "gerente": {
                String consultaNombreA = "SELECT nombree FROM empleados WHERE nom_usr = '" + usr + "'";
                String nombreG = cnx.obtenerDato(consultaNombreA);
                FGerente fg = new FGerente(nombreG);
                cnx.desconectar();
                this.dispose();
                fg.setVisible(true);
                break;
            }

            case "cajero": {
                String consultaNombreC = "SELECT nombree FROM empleados WHERE nom_usr = '" + usr + "'";
                String nombreC = cnx.obtenerDato(consultaNombreC);
                FCajero fc = new FCajero(nombreC);
                cnx.desconectar();
                this.dispose();
                fc.setVisible(true);
                break;
            }

            case "cocinero": {
                String consultaNombreCo = "SELECT nombree FROM empleados WHERE nom_usr = '" + usr + "'";
                String nombreCo = cnx.obtenerDato(consultaNombreCo);
                FCocinero fco = new FCocinero(nombreCo);
                cnx.desconectar();
                this.dispose();
                fco.setVisible(true);
                break;
            }

            case "mesero": {
                String consultaNombreCo = "SELECT nombree FROM empleados WHERE nom_usr = '" + usr + "'";
                String nombreM = cnx.obtenerDato(consultaNombreCo);
                FMesero fm = new FMesero(nombreM);
                cnx.desconectar();
                this.dispose();
                fm.setVisible(true);
                break;
            }

            case "":
                JOptionPane.showMessageDialog(this, "Credenciales incorrectas");
                intentos++;

                if (intentos >= 3) {
                    JOptionPane.showMessageDialog(this, "Número de intentos excedidos");
                    cnx.desconectar();
                    System.exit(0);
                }
                break;

            default:
                JOptionPane.showMessageDialog(this, "Rol no reconocido");
                break;
        }

    }//GEN-LAST:event_BAceptarActionPerformed

